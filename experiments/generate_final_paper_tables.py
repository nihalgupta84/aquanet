#!/usr/bin/env python3
"""Generate every manuscript table from the immutable result JSONs.

Same rule as the figure script: no result literal appears in this file. Each table is
written twice -- a `.tex` fragment that `main.tex` \\input's, and a `.csv` with the same
numbers at full precision so a reader can check the rounding.

    python experiments/generate_final_paper_tables.py
"""
import sys, csv, argparse
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'experiments'))
import paper_data as D

OUT = ROOT / 'paper_final' / 'tables'


def emit(name, header, rows, caption, label, align=None, note=None, small='\\scriptsize',
         wide=False):
    """Write one table as a booktabs .tex fragment and a matching .csv.

    `wide` emits a two-column-spanning `table*`. Tables with more than about six columns do
    not fit an IEEEtran column at \\scriptsize, and silently overfull boxes are how a
    truncated number reaches a reviewer.
    """
    OUT.mkdir(parents=True, exist_ok=True)
    align = align or ('l' + 'r' * (len(header) - 1))
    env, width = ('table*', '\\textwidth') if wide else ('table', '\\columnwidth')
    lines = [f'% generated by experiments/generate_final_paper_tables.py -- do not edit',
             f'\\begin{{{env}}}[t]\\centering',
             f'\\caption{{{caption}}}\\label{{{label}}}{small}',
             f'\\begin{{tabular}}{{{align}}}\\toprule',
             ' & '.join(header) + ' \\\\\\midrule']
    for r in rows:
        lines.append(' & '.join(str(c) for c in r) + ' \\\\')
    lines.append('\\bottomrule\\end{tabular}')
    if note:
        lines.append(f'\\\\[2pt]\\begin{{minipage}}{{{width}}}\\footnotesize {note}'
                     f'\\end{{minipage}}')
    lines.append(f'\\end{{{env}}}')
    (OUT / f'{name}.tex').write_text('\n'.join(lines) + '\n')
    with (OUT / f'{name}.csv').open('w', newline='') as fh:
        w = csv.writer(fh)
        w.writerow([h.replace('\\', '').replace('$', '') for h in header])
        w.writerows(rows)
    print(f'  {name}.tex / .csv  ({len(rows)} rows)')


def tex(s):
    """Escape a raw identifier (run tag, filename, note text) for LaTeX text mode."""
    for a, b in (('\\', '\\textbackslash '), ('_', '\\_'), ('&', '\\&'), ('%', '\\%'),
                 ('#', '\\#'), ('$', '\\$'), ('{', '\\{'), ('}', '\\}')):
        s = str(s).replace(a, b)
    return s


def bold(x, cond):
    return f'\\textbf{{{x}}}' if cond else x


def f(x, n=4):
    return f'{x:.{n}f}'.lstrip('0') if 0 < x < 1 else f'{x:.{n}f}'


