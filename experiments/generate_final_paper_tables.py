def t_dataset():
    s = D.dataset_stats()
    d1 = s['sets']['D1']
    rows = []
    for c in D.CLASSES:
        tr = d1['counts_by_split_label']['train'].get(c, 0)
        va = d1['counts_by_split_label']['val'].get(c, 0)
        te = d1['counts_by_split_label']['test'].get(c, 0)
        rows.append([c, tr, va, te, tr + va + te])
    rows.append(['\\textbf{total}'] + [f'\\textbf{{{v}}}' for v in
                                       (1956, 416, 427, d1['n'])])
    for k, name in (('D2', 'D2 (adaptation, real video frames)'),
                    ('D3', 'D3 (out-of-distribution test)')):
        if k in s['sets']:
            rows.append([name, '--', '--', '--', s['sets'][k]['n']])
    emit('dataset_composition', ['Class', 'Train', 'Val', 'Test', 'Total'], rows,
         'Dataset composition. D1 is the primary set; the split is fixed and never '
         'resampled. D1 originates from a public Kaggle collection and contains '
         'AI-generated imagery, so it is consolidated and audited here, not introduced '
         'as a novel dataset.', 'tab:dataset',
         note=f"D1 spans {d1['n_distinct_resolutions']} distinct source resolutions; "
              f"{d1['images_in_multi_split_resolution_group']} of {d1['n']} images sit in a "
              f"resolution group that spans more than one split. Aspect ratios range "
              f"{d1['aspect_ratio']['min']:.2f}--{d1['aspect_ratio']['max']:.2f} and "
              f"preprocessing resizes to $224\\times224$ without preserving them.")


def t_protocol():
    c = D.training_config()
    e = D.env()
    keys = [('img_size', 'Input resolution', lambda v: f'${v}\\times{v}$'),
            ('epochs', 'Maximum epochs', str), ('patience', 'Early-stopping patience', str),
            ('batch', 'Batch size', str), ('warmup_epochs', 'Warmup epochs', str),
            ('weight_decay', 'Weight decay', lambda v: f'{v:g}'),
            ('clip_grad', 'Gradient clipping', lambda v: f'{v:g}'),
            ('loss', 'Loss', lambda v: {'wce': 'weighted cross entropy'}.get(v, v)),
            ('balance', 'Class balancing', lambda v: f'{v}, normalised to mean 1'),
            ('amp', 'Mixed precision', lambda v: 'yes' if v else 'no')]
    rows = [[label, fmt(c[k])] for k, label, fmt in keys if k in c]
    rows += [['Optimiser parameter groups', 'pretrained trunk vs.\\ fresh modules'],
             ['LR schedule', 'linear warmup then cosine'],
             ['Checkpoint selection', 'validation macro-F1'],
             ['Tuning budget', '6 trials per model (Stage T), one seed'],
             ['Promotion seeds', ', '.join(str(s) for s in D.SEEDS)],
             ['Torch / CUDA', f"{e.get('torch','?')} / {e.get('cuda','?')}"],
             ['GPU', e.get('gpu', '?')]]
    emit('protocol', ['Setting', 'Value'], rows,
         'Training protocol. Every entry is identical for all ten architectures; only the '
         'learning rate and backbone multiplier are selected per model, from the same '
         'six-trial grid.', 'tab:protocol', align='lp{0.60\\columnwidth}')


def t_lr_selection():
    s = D.sensitivity()
    rows = []
    for n in sorted(s, key=lambda n: -s[n]['spread']):
        r = s[n]
        rows.append([n, r['n_trials'], f"${r['best_lr']:g}$", f"${r['best_mult']:g}$",
                     f(r['best_val_mf1']), f(r['worst_val_mf1']),
                     bold(f(r['spread']), r['spread'] == max(v['spread'] for v in s.values()))])
    emit('lr_selection', ['Model', 'Trials', 'LR', 'Backbone $\\times$', 'Best val \\mf{}',
                          'Worst val \\mf{}', 'Spread'], rows,
         'Per-model outcome of the identical six-trial tuning grid. Selection uses '
         'validation macro-F1 only. The spread is how much the shared-hyperparameter '
         'protocol could have cost each model.', 'tab:lr', wide=True,
         note='Grid: $\\eta\\in\\{10^{-4},3\\times10^{-4},10^{-3}\\}$ crossed with backbone '
              'multiplier $\\in\\{0.1,1.0\\}$.')


def t_main_ranking():
    rows_p = D.stage_p()
    best = max(r['mf1'] for r in rows_p)
    rows = [[r['name'], f"{r['params_m']:.2f}", f(r['val_mf1']),
             f"{f(r['acc'])} $\\pm$ {f(r['acc_sd'])}",
             bold(f"{f(r['mf1'])} $\\pm$ {f(r['mf1_sd'])}", r['mf1'] == best)]
            for r in rows_p]
    emit('main_ranking', ['Model', 'Params (M)', 'Val \\mf{}', 'Test acc.\\ $\\pm$ sd',
                          'Test \\mf{} $\\pm$ sd'], rows,
         f'Stage-P results after per-model tuning, mean $\\pm$ sample sd over five seeds '
         f'({", ".join(str(s) for s in D.SEEDS)}). Selection is on validation macro-F1; '
         f'test values are reported, never used to choose.', 'tab:main', wide=True,
         note='The test split holds 427 images, so accuracy differences are exact '
              'multiples of $1/427=0.0023$.')


def t_significance():
    sel = D.selected_model()
    rows = []
    for metric, label in (('macro_f1', 'macro-F1'), ('accuracy', 'accuracy')):
        for c in sorted(D.paired_tests(metric), key=lambda z: z['paired_t_p']):
            sig = c['paired_t_p_holm'] < 0.05
            rows.append([c['name'], label, f"{c['mean_diff']:+.4f}",
                         f"{c['wins']}/{c['n_seeds']}", f"{c['cohens_dz']:.2f}",
                         f"{c['paired_t_p']:.4f}",
                         bold(f"{c['paired_t_p_holm']:.4f}", sig)])
    emit('significance', ['Compared with ' + sel, 'Metric', '$\\Delta$', 'Wins', '$d_z$',
                          '$p$', '$p_{\\mathrm{Holm}}$'], rows,
         f'Paired seed-level $t$ tests of {sel} against every other finalist, '
         f'Holm-corrected within each metric across nine comparisons. Bold marks '
         f'$p_{{\\mathrm{{Holm}}}}<0.05$.', 'tab:sig', wide=True,
         note='Wilcoxon is not reportable at $n=5$: the smallest attainable two-sided '
              '$p$ is 0.062 regardless of effect size. Prediction-level bootstrap and '
              'McNemar tests exist for seed 7 only and are reported as such.')


def t_calibration():
    cal = D.calibration()
    acc = {r['name']: r for r in D.stage_p()}
    names = sorted(cal['ece_raw'], key=lambda n: cal['ece_raw'][n]['mean'])
    bT = min(abs(cal['T'][n]['mean'] - 1) for n in names)
    bE = min(cal['ece_raw'][n]['mean'] for n in names)
    bC = min(cal['ece_cal'][n]['mean'] for n in names)
    rows = []
    for n in names:
        rows.append([n,
                     bold(f"{cal['T'][n]['mean']:.3f}", abs(cal['T'][n]['mean'] - 1) == bT),
                     bold(f(cal['ece_raw'][n]['mean']), cal['ece_raw'][n]['mean'] == bE),
                     bold(f(cal['ece_cal'][n]['mean']), cal['ece_cal'][n]['mean'] == bC),
                     f(cal['nll_raw'][n]['mean']), f(cal['brier_raw'][n]['mean']),
                     f(acc[n]['mf1'])])
    emit('calibration', ['Model', 'Fitted $T$', 'ECE raw', 'ECE cal.', 'NLL', 'Brier',
                         'Test \\mf{}'], rows,
         'Calibration over five seeds, sorted by uncalibrated ECE. $T$ is fitted on the '
         'validation split; ECE uses 15 equal-width confidence bins. Test macro-F1 is '
         'repeated from Table~\\ref{tab:main} so the calibration ranking is never read '
         'apart from the accuracy ranking.', 'tab:calibration', wide=True,
         note='Bold marks the best column value; for $T$, best means closest to the '
              'ideal $T=1$. Values come from \\texttt{reports/stageD\\_calibration.json}, '
              'the only source carrying the fitted temperature.')


def t_calibration_tests():
    rows = []
    for r in D.paired_calibration_tests('T', 'AquaNet-no-neck', absolute_from=1.0):
        rows.append([r['name'], f"{r['mean_diff']:+.4f}", f"{r['wins']}/{r['n']}",
                     f"{r['p']:.5f}", bold(f"{r['p_holm']:.5f}", r['p_holm'] < 0.05)])
    emit('calibration_tests', ['Compared with AquaNet-no-neck', '$\\Delta|T-1|$', 'Wins',
                              '$p$', '$p_{\\mathrm{Holm}}$'], rows,
         'Paired seed-level $t$ tests of distance from the ideal temperature, '
         '$|T-1|$, AquaNet-no-neck against each of the nine other models. A positive '
         '$\\Delta$ means the other model sits further from $T=1$.', 'tab:caltests',
         note='Holm correction across the nine comparisons. The same test on '
              'uncalibrated ECE does \\emph{not} reach significance against Swin-T '
              '($p_{\\mathrm{Holm}}>0.3$), so the ECE result is stated as a ranking, '
              'not as a significant difference.')


def t_per_class():
    pc = D.per_class_f1()
    order = [r['name'] for r in D.stage_p()]
    supp = D.confusion(order[0]).sum(1) // len(D.SEEDS)
    rows = [['Support'] + [str(int(s)) for s in supp]]
    for n in order:
        rows.append([n] + [f(pc[n][c]['mean']) for c in D.CLASSES])
    emit('per_class', ['Model'] + [c[:6] for c in D.CLASSES], rows,
         'Per-class F1, five-seed mean. Rows follow the macro-F1 ranking. The two '
         'smallest classes, oil and clean, carry the ranking: they hold 24 and 41 test '
         'images respectively.', 'tab:perclass', small='\\tiny', wide=True)


def t_ablation():
    fa = D.factorial()
    mt = D.matched_triplets()
    rows = []
    for axis, label in (('marginal_head', 'Head'), ('marginal_msrb', 'MSRB'),
                        ('marginal_csab', 'CSAB')):
        levels = fa[{'marginal_head': 'heads', 'marginal_msrb': 'msrb',
                     'marginal_csab': 'csab'}[axis]]
        best = max(fa[axis].values())
        for lvl in levels:
            rows.append([label, lvl.replace('_', '-'),
                         bold(f(fa[axis][lvl]), fa[axis][lvl] == best)])
    emit('ablation_marginals', ['Factor', 'Level', 'Marginal test \\mf{}'], rows,
         f"Marginal means of the balanced {fa['n_runs']}-run factorial "
         f"({fa['n_cells']} cells $\\times$ {len(fa['seeds'])} seeds). Marginals average "
         f"cell means, so no cell is weighted more heavily than another.", 'tab:ablation',
         align='llr',
         note=f"A further {fa['n_aux_runs']} Stage-B runs are one-off sensitivity "
              f"experiments on a single cell (a $\\lambda_{{\\mathrm{{mix}}}}$ sweep and an "
              f"\\texttt{{uncertain\\_binary=exclude}} variant); they are excluded here "
              f"because averaging them in lets one cell move an axis it does not belong to.")

    rows = []
    for k, label in (('on_vs_matched', 'MSRB vs.\\ MatchedNeck (capacity held constant)'),
                     ('on_vs_off', 'MSRB vs.\\ no neck (capacity differs)'),
                     ('matched_vs_off', 'MatchedNeck vs.\\ no neck (capacity alone)')):
        r = mt[k]
        rows.append([label, r['n'], f"{r['mean_diff']:+.4f}", f"{r['wins']}/{r['n']}"])
    emit('matched_neck', ['Comparison', '$n$ pairs', '$\\Delta$ \\mf{}', 'Wins'], rows,
         'Head-, CSAB- and seed-matched neck comparisons within the balanced factorial. '
         'MatchedNeck carries the same 3{,}407{,}872 convolution weights and 3{,}072 '
         'normalisation parameters as MSRB with none of its multi-scale structure, which '
         'is what separates "MSRB helps" from "3.4M extra parameters help".',
         'tab:matched', align='p{0.44\\columnwidth}rrr')


def t_robustness():
    co = D.corruptions()
    names = [r['name'] for r in D.stage_p()]
    rows = []
    for n in names:
        rows.append([n] + [f(co['by_corruption'][c][n]['mean'], 3) for c in co['names']]
                    + [bold(f(co['mean_degradation'][n]['mean'], 3),
                            co['mean_degradation'][n]['mean'] ==
                            min(v['mean'] for v in co['mean_degradation'].values()))])
    emit('robustness', ['Model'] + [c.replace('_', ' ') for c in co['names']] + ['Mean'],
         rows,
         'Macro-F1 degradation under nine corruptions, averaged over five severities and '
         'five seeds. Lower is better; bold marks the most robust model.', 'tab:robust',
         small='\\tiny', wide=True)


def t_ood():
    z = D.zeroshot()
    a = D.adaptation()
    names = sorted(z['mf1'], key=lambda n: -z['mf1'][n]['mean'])
    rows = [[n, f"{f(z['acc'][n]['mean'])}", f"{f(z['mf1'][n]['mean'])} $\\pm$ "
             f"{f(z['mf1'][n]['sd'])}", f(z['false_clean'][n]['mean'])] for n in names]
    emit('ood', ['Model', 'D3 acc.', 'D3 \\mf{} $\\pm$ sd', 'False-clean rate'], rows,
         'Zero-shot transfer to D3 (146 images, 14--26 per class), five seeds. No D3 '
         'image is used for training or selection at any point.', 'tab:ood',
         note='D3 is a small held-out probe, not a benchmark. The false-clean rate is the '
              'fraction of contaminated images called clean, the error that matters most '
              'for a screening application.')

    rows = [['0 (zero-shot)', 0, f(a['zero_shot_mf1']), '--']]
    for p in a['points']:
        rows.append([f"{p['pct']}", p['n_images'], f(p['mf1']), f(p['sd'])])
    emit('adaptation', ['D2 data used (\\%)', 'Images', 'D3 \\mf{}', 'sd'], rows,
         f"Fine-tuning on D2 and re-testing on D3, mean over seeds "
         f"{', '.join(str(s) for s in a['seeds'])}, starting from the "
         f"DeiT-Small seed-42 run.",
         'tab:adapt',
         note='The 75\\% point is below the 50\\% point. With three seeds and 146 test '
              'images this ordering is not resolvable and no monotone trend is claimed.')


def t_complexity():
    cx = D.complexity()
    rows_p = {r['name']: r for r in D.stage_p()}
    names = sorted(rows_p, key=lambda n: cx['params_m'][n]['mean'])
    header = ['Model', 'Params (M)', 'GPU ms', 'CPU ms', 'Peak MiB', 'Test \\mf{}']
    rows = [[n, f"{cx['params_m'][n]['mean']:.2f}",
             f"{cx['latency_cuda_ms'][n]['mean']:.1f}",
             f"{cx['latency_cpu_ms'][n]['mean']:.1f}",
             f"{cx['peak_mem_mib'][n]['mean']:.0f}", f(rows_p[n]['mf1'])] for n in names]
    note = ('Latency is per evaluation batch on the GPU recorded in Table~\\ref{tab:protocol} '
            'and is not a deployment measurement.')
    if not cx['gflops_available']:
        # A null column is worse than no column, and an analytic estimate presented as a
        # measurement is worse than either.
        note += f" GFLOPs are omitted: {cx['gflops_note']}. They are not estimated analytically."
    emit('complexity', header, rows,
         'Complexity and cost. Parameter counts are exact; timings are means over five '
         'seeds on identical hardware.', 'tab:complexity', wide=True, note=note)


def t_explanations():
    e = D.explanations()
    names = sorted(e['deletion'], key=lambda n: e['deletion'][n]['mean'])
    rows = [[n, f(e['deletion'][n]['mean']), f(e['insertion'][n]['mean']),
             f(e['insertion'][n]['mean'] - e['deletion'][n]['mean'])] for n in names]
    emit('explanations', ['Model', 'Deletion AUC', 'Insertion AUC', 'Gap'], rows,
         f"Grad-CAM deletion and insertion AUC over {e['n_images']} images, five-seed "
         f"means. Lower deletion and higher insertion indicate saliency that tracks "
         f"evidence the model uses.", 'tab:explain',
         note='Gradient maps are not architecture-neutral and standard Grad-CAM is poorly '
              'matched to transformer token mixing, so these are within-family '
              'diagnostics, not a claim that one architecture is more interpretable.')


def t_classical():
    cl = D.classical()
    if not cl:
        print('  (skipped classical: reports/stageG_classical.json absent)')
        return
    deep = {r['name']: r for r in D.stage_p()}
    rows = []
    for k, v in sorted(cl['models'].items(), key=lambda z: -z[1]['test_macro_f1_mean']):
        rows.append([k.replace('_', ' '), f(v['val_macro_f1']),
                     f"{f(v['test_acc_mean'])} $\\pm$ {f(v['test_acc_sd'])}",
                     f"{f(v['test_macro_f1_mean'])} $\\pm$ {f(v['test_macro_f1_sd'])}"])
    for n in ('MobileNetV2', 'DenseNet-121', 'AquaNet-full', 'Swin-T'):
        r = deep[n]
        rows.append([f'\\emph{{{n}}} (deep)', f(r['val_mf1']),
                     f"{f(r['acc'])} $\\pm$ {f(r['acc_sd'])}",
                     f"{f(r['mf1'])} $\\pm$ {f(r['mf1_sd'])}"])
    m = cl['_meta']
    emit('classical', ['Model', 'Val \\mf{}', 'Test acc.\\ $\\pm$ sd', 'Test \\mf{} $\\pm$ sd'],
         rows,
         f"Classical baselines on hand-crafted colour and texture features "
         f"({m['feature_dim']} dimensions: RGB and HSV histograms, LBP at two scales, GLCM "
         f"Haralick descriptors and HOG), same splits and same six-trial budget as the deep "
         f"models. Four deep models are repeated for reference.", 'tab:classical',
         note='Logistic regression and the RBF SVM are deterministic given fixed data, so '
              'their across-seed sd is 0 by construction rather than by stability.')


def t_shortcut():
    sc = D.shortcut()
    if not sc:
        print('  (skipped shortcut: reports/stageH_shortcut.json absent)')
        return
    best = max(r['mf1'] for r in D.stage_p())
    rows = [['Majority class', '--', f(sc['majority_baseline']['accuracy']),
             f(sc['majority_baseline']['macro_f1'])]]
    labels = {'metadata_only': 'File metadata only (no pixels)',
              'mean_colour_only': 'Mean and sd of RGB channels'}
    for k, p in sc['probes'].items():
        rows.append([labels.get(k, k), p['n_features'],
                     f"{f(p['accuracy_mean'])} $\\pm$ {f(p['accuracy_sd'])}",
                     f"{f(p['macro_f1_mean'])} $\\pm$ {f(p['macro_f1_sd'])}"])
    rows.append(['\\emph{Best deep model}', '--',
                 f(max(r['acc'] for r in D.stage_p())), f(best)])
    emit('shortcut', ['Probe', 'Features', 'Test acc.\\ $\\pm$ sd', 'Test \\mf{} $\\pm$ sd'],
         rows,
         'Shortcut probes on the D1 test split, five seeds. The metadata probe uses image '
         'width, height, aspect ratio, pixel count, file size, bytes per pixel and the '
         'JPEG quantisation tables; no pixel content reaches it.', 'tab:shortcut', align='p{0.34\\columnwidth}rrr',
         note='Every model in this study sees the same inputs and the same splits, so the '
              'relative ranking is unaffected. Absolute accuracy on D1 is nonetheless '
              'inflated relative to a deployment in which source identity carries no '
              'information about the label.')


def t_ece_sources():
    a = D.ece_source_agreement()
    rows = [[r['name'], f(r['pipeline_ece'], 5), f(r['stageD_ece_raw'], 5),
             f"{r['abs_diff']:.5f}"] for r in a['rows']]
    emit('ece_sources', ['Model', 'Training pipeline', 'Evaluation suite', '$|\\Delta|$'],
         rows,
         'Agreement between the two independent ECE implementations. The manuscript '
         'quotes the evaluation-suite column throughout, because it is the only one '
         'carrying the fitted temperature.', 'tab:ecesources',
         note=f"The two code paths agree to within "
              f"${a['max_abs_diff']:.1e}$ on all ten models, which is below the fourth "
              f"decimal for eight of them and below the third for all ten.")


TABLES = {
    'dataset': t_dataset, 'protocol': t_protocol, 'lr_selection': t_lr_selection,
    'main_ranking': t_main_ranking, 'significance': t_significance,
    'calibration': t_calibration, 'calibration_tests': t_calibration_tests,
    'per_class': t_per_class, 'ablation': t_ablation, 'robustness': t_robustness,
    'ood': t_ood, 'complexity': t_complexity, 'explanations': t_explanations,
    'classical': t_classical, 'ece_sources': t_ece_sources, 'shortcut': t_shortcut,
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', nargs='*', choices=sorted(TABLES))
    ap.add_argument('--out', default=None)
    a = ap.parse_args()
    global OUT
    if a.out:
        OUT = Path(a.out).resolve()
    print(f'writing tables to {OUT}')
    for name in (a.only or TABLES):
        TABLES[name]()
    return 0


if __name__ == '__main__':
    sys.exit(main())
